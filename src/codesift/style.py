"""Infer a project's existing code style so codesift enforces *its* conventions."""

from __future__ import annotations

import io
import re
import tokenize
from collections import Counter
from dataclasses import dataclass, field
from typing import Dict, List

from .config import Config
from .engine import discover, load_source

_COMMON_LIMITS = [79, 80, 88, 100, 110, 120, 140]


@dataclass
class StyleProfile:
    language: str
    files: int = 0
    indent_style: str = "space"
    indent_size: int = 4
    quote_style: str = "auto"
    max_line_length: int = 120
    evidence: Dict[str, str] = field(default_factory=dict)


def infer(cfg: Config) -> Dict[str, StyleProfile]:
    by_lang: Dict[str, List] = {}
    for rel in discover(cfg):
        src = load_source(cfg.root, rel)
        if src and src.language in ("python", "javascript", "typescript"):
            key = "javascript" if src.language == "typescript" else src.language
            by_lang.setdefault(key, []).append(src)
    return {lang: _profile(lang, files) for lang, files in by_lang.items()}


def _profile(lang: str, files) -> StyleProfile:
    p = StyleProfile(language=lang, files=len(files))
    tabs = spaces = 0
    widths: Counter = Counter()
    lengths: List[int] = []
    quotes: Counter = Counter()
    for src in files:
        prev = 0
        for line in src.lines:
            if not line.strip():
                continue
            lengths.append(len(line))
            indent = line[: len(line) - len(line.lstrip(" \t"))]
            if indent.startswith("\t"):
                tabs += 1
            elif indent:
                spaces += 1
                n = len(indent)
                if n > prev and n - prev in (2, 4, 8):
                    widths[n - prev] += 1
                prev = n
            else:
                prev = 0
        quotes.update(_count_quotes(src))

    p.indent_style = "tab" if tabs > spaces else "space"
    if widths:
        p.indent_size = widths.most_common(1)[0][0]
    p.evidence["indent"] = f"{spaces} space-indented vs {tabs} tab-indented lines; step sizes {dict(widths)}"

    if lengths:
        lengths.sort()
        p95 = lengths[int(len(lengths) * 0.99) - 1] if len(lengths) > 1 else lengths[0]
        p.max_line_length = next((x for x in _COMMON_LIMITS if x >= p95), 160)
        p.evidence["line length"] = f"99th percentile line is {p95} chars"

    single, double = quotes.get("'", 0), quotes.get('"', 0)
    total = single + double
    if total >= 20:
        if single / total >= 0.8:
            p.quote_style = "single"
        elif double / total >= 0.8:
            p.quote_style = "double"
    p.evidence["quotes"] = f"{single} single-quoted vs {double} double-quoted strings"
    return p


def _count_quotes(src) -> Counter:
    c: Counter = Counter()
    if src.language == "python":
        try:
            for tok in tokenize.generate_tokens(io.StringIO(src.text).readline):
                if tok.type == tokenize.STRING:
                    body = tok.string.lstrip("rRbBuUfF")
                    if body[:3] in ('"""', "'''"):
                        continue
                    c[body[0]] += 1
        except (tokenize.TokenError, SyntaxError, IndentationError):
            pass
    else:
        for m in re.finditer(r"(?<![\\\w])(['\"])(?:\\.|(?!\1).)*?\1", src.text):
            c[m.group(1)] += 1
    return c


def render_config(profiles: Dict[str, StyleProfile]) -> str:
    """Produce a commented .codesift.toml from inferred style profiles."""
    primary = max(profiles.values(), key=lambda p: p.files) if profiles else StyleProfile("python")
    lines = [
        "# codesift configuration — generated by `codesift init` from your existing code.",
        "# Docs: every key is optional. Rule IDs or names work anywhere a rule is expected.",
        "[codesift]",
        f"max-line-length = {primary.max_line_length}",
        f'indent-style = "{primary.indent_style}"',
        f"indent-size = {primary.indent_size}",
        f'quote-style = "{primary.quote_style}"   # "single", "double", or "auto" (don\'t enforce)',
        "max-complexity = 12",
        'fail-on = "error"          # exit non-zero on: "error", "warning", or "info"',
        'baseline = ".codesift-baseline.json"   # created by `codesift baseline`',
        "",
        "# Paths to skip in addition to the built-in defaults (node_modules, dist, .venv, ...).",
        "extend-exclude = []",
        "",
        "# Turn off rules entirely, e.g. [\"G020\", \"no-var\"].",
        "disable = []",
        "",
        "# Change a rule's severity.",
        "[codesift.severity]",
        '# G003 = "warning"',
        "",
        "# Relax rules for tests.",
        "[[codesift.overrides]]",
        'paths = ["tests/**", "**/test_*.py", "**/*.test.*", "**/*.spec.*"]',
        'disable = ["PY021", "PY025", "PY026", "JS002"]',
    ]
    for lang, p in profiles.items():
        if p is primary:
            continue
        if (p.indent_size, p.indent_style, p.quote_style, p.max_line_length) != (
                primary.indent_size, primary.indent_style, primary.quote_style, primary.max_line_length):
            globs = '["**/*.py"]' if lang == "python" else '["**/*.js", "**/*.jsx", "**/*.ts", "**/*.tsx", "**/*.mjs"]'
            lines += [
                "",
                f"# {lang} files follow a different convention in this repo.",
                "[[codesift.overrides]]",
                f"paths = {globs}",
                f"max-line-length = {p.max_line_length}",
                f'indent-style = "{p.indent_style}"',
                f"indent-size = {p.indent_size}",
                f'quote-style = "{p.quote_style}"',
            ]
    return "\n".join(lines) + "\n"
